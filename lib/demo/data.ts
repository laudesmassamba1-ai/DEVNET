/**
 * Jeu de données de démonstration.
 *
 * Il n'existe que pour le mode démo (backend injoignable). Il est
 * volontairement « credential-shaped » : mêmes colonnes, mêmes types,
 * mêmes chaînes de caractères que celles que renvoie Postgres — pour que
 * le code applicatif ne fasse aucune différence entre vrai et faux backend.
 */

const t0 = Date.parse("2026-10-03T14:00:00Z");

/** Date ISO décalée de `ms` millisecondes avant l'instant de référence. */
function ago(ms: number): string {
  return new Date(t0 - ms).toISOString();
}

/** Une heure et une minute, en millisecondes. */
const HOUR = 3_600_000;
const MIN = 60_000;

